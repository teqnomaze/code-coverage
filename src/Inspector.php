<?php

declare(strict_types=1);

namespace Teqnomaze\Coverage;

use InvalidArgumentException;
use RuntimeException;

/**
 * Checks a PHPUnit `clover.xml` report against a minimum coverage threshold.
 */
class Inspector
{
    /**
     * ANSI sequence for white text on a green background.
     */
    private const ANSI_PASS = "\033[42;37m";

    /**
     * ANSI sequence for white text on a red background.
     */
    private const ANSI_FAIL = "\033[41;37m";

    /**
     * ANSI sequence that resets all colors.
     */
    private const ANSI_RESET = "\033[0m";

    /**
     * The location of the `clover.xml` file generated by PHPUnit.
     *
     * @var string
     */
    private string $clover;

    /**
     * The minimum acceptable coverage percentage (1 to 100).
     *
     * @var int
     */
    private int $threshold;

    /**
     * The measured coverage percentage, or null before the check has run.
     *
     * @var float|null
     */
    private ?float $coverage = null;

    /**
     * The coverage result message, or null before the check has run.
     *
     * @var string|null
     */
    private ?string $message = null;

    /**
     * Whether the measured coverage met the threshold.
     *
     * @var bool
     */
    private bool $passed = false;

    /**
     * Create the inspector.
     *
     * @param string $clover    The clover.xml file path.
     * @param int    $threshold The minimum coverage percentage (1 to 100).
     *
     * @throws InvalidArgumentException When the threshold is out of range.
     */
    public function __construct(string $clover, int $threshold = 80)
    {
        $this->setClover($clover);
        $this->setThreshold($threshold);
    }

    /**
     * Run the coverage check.
     *
     * @return self
     *
     * @throws RuntimeException When the clover file is missing or invalid.
     */
    public function check(): self
    {
        if (!is_file($this->clover)) {
            throw new RuntimeException(sprintf('Clover file not found: %s', $this->clover));
        }

        $previous = libxml_use_internal_errors(true);
        $xml = simplexml_load_file($this->clover);
        libxml_clear_errors();
        libxml_use_internal_errors($previous);

        if ($xml === false) {
            throw new RuntimeException(sprintf('Invalid clover file: %s', $this->clover));
        }

        $metrics = $xml->xpath('/coverage/project/metrics');

        if (empty($metrics)) {
            throw new RuntimeException(sprintf('No project metrics found in clover file: %s', $this->clover));
        }

        $total = (int) $metrics[0]['elements'];
        $covered = (int) $metrics[0]['coveredelements'];

        $this->coverage = $total > 0 ? ($covered / $total) * 100 : 0.0;
        $this->passed = $this->coverage >= $this->threshold;

        $this->message = sprintf(
            'Code coverage is %d%%, which is %s the accepted %d%%',
            (int) floor($this->coverage),
            $this->passed ? 'above' : 'below',
            $this->threshold,
        );

        return $this;
    }

    /**
     * Print the coverage result.
     *
     * @param bool|null $colored Force colors on or off, or null to detect terminal support.
     *
     * @return void
     *
     * @throws RuntimeException When the check has to run and the clover file is missing or invalid.
     */
    public function output(?bool $colored = null): void
    {
        if ($this->message === null) {
            $this->check();
        }

        $text = (string) $this->message;

        if ($colored ?? $this->supportsColor()) {
            $code = $this->passed ? self::ANSI_PASS : self::ANSI_FAIL;
            $text = $code . $text . self::ANSI_RESET;
        }

        echo PHP_EOL . $text . str_repeat(PHP_EOL, 2);
    }

    /**
     * Get the process exit code for the result (0 on pass, 1 on fail).
     *
     * @return int
     */
    public function getExitCode(): int
    {
        return $this->passed ? 0 : 1;
    }

    /**
     * Get the clover file path.
     *
     * @return string
     */
    public function getClover(): string
    {
        return $this->clover;
    }

    /**
     * Set the clover file path.
     *
     * @param string $clover The clover file path.
     *
     * @return self
     */
    public function setClover(string $clover): self
    {
        $this->clover = $clover;

        return $this;
    }

    /**
     * Get the threshold percentage.
     *
     * @return int
     */
    public function getThreshold(): int
    {
        return $this->threshold;
    }

    /**
     * Set the threshold percentage.
     *
     * @param int $threshold The minimum coverage percentage (1 to 100).
     *
     * @return self
     *
     * @throws InvalidArgumentException When the threshold is out of range.
     */
    public function setThreshold(int $threshold): self
    {
        if ($threshold < 1 || $threshold > 100) {
            throw new InvalidArgumentException('Threshold must be between 1 and 100.');
        }

        $this->threshold = $threshold;

        return $this;
    }

    /**
     * Get the measured coverage percentage.
     *
     * @return float|null Null until the check has run.
     */
    public function getCoverage(): ?float
    {
        return $this->coverage;
    }

    /**
     * Get the result message.
     *
     * @return string|null Null until the check has run.
     */
    public function getMessage(): ?string
    {
        return $this->message;
    }

    /**
     * Whether the coverage met the threshold.
     *
     * @return bool
     */
    public function hasPassed(): bool
    {
        return $this->passed;
    }

    /**
     * Whether standard output can display ANSI colors.
     *
     * @return bool
     */
    private function supportsColor(): bool
    {
        return getenv('NO_COLOR') === false
            && function_exists('stream_isatty')
            && stream_isatty(STDOUT);
    }
}
